// Generates app/map-data.ts: an accurate Albers-USA projection of the
// continental US (state outlines + borders) plus projected screen
// coordinates for every Cowabunga farm and its nearest major city.
//
// Run: node scripts/generate-map-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { geoAlbersUsa, geoPath } from "d3-geo";
import { feature, mesh } from "topojson-client";
import { presimplify, simplify, quantile } from "topojson-simplify";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

// Standard us-atlas display projection for a 975 x 610 canvas.
const WIDTH = 975;
const HEIGHT = 610;
const projection = geoAlbersUsa().scale(1300).translate([WIDTH / 2, 305]);
const pathGen = geoPath(projection);

const rawTopo = JSON.parse(
  readFileSync(resolve(root, "node_modules/us-atlas/states-10m.json"), "utf8"),
);

// The map renders small, so the 10m detail is wasteful and janky to repaint.
// Presimplify then drop ~93% of the least-important points (keep the coarse
// silhouette). This shrinks the path ~10x and lets it repaint smoothly.
const presimplified = presimplify(rawTopo);
const minWeight = quantile(presimplified, 0.07);
const topo = simplify(presimplified, minWeight);

// Every Cowabunga farm is in the lower 48, so drop the Alaska (FIPS "02") and
// Hawaii ("15") insets for a clean, tight continental map.
topo.objects.states.geometries = topo.objects.states.geometries.filter(
  (g) => g.id !== "02" && g.id !== "15",
);

const states = feature(topo, topo.objects.states);
const nation = mesh(topo, topo.objects.states, (a, b) => a === b); // outer coastline
const borders = mesh(topo, topo.objects.states, (a, b) => a !== b); // internal borders

// Round every coordinate in an SVG path to 1 decimal to cut bundle size;
// at this scale the visual difference is imperceptible.
const trim = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));

const nationPath = trim(pathGen(nation));
const bordersPath = trim(pathGen(borders));
const statesFill = trim(pathGen(states)); // filled land mass

// Tight viewBox around the continental US so the map fills its frame
// (the raw Albers canvas leaves large empty margins).
const [[bx0, by0], [bx1, by1]] = pathGen.bounds(states);
const PAD = 16;
const vbX = Math.round(bx0 - PAD);
const vbY = Math.round(by0 - PAD);
const vbW = Math.round(bx1 - bx0 + PAD * 2);
const vbH = Math.round(by1 - by0 + PAD * 2);
const viewBox = `${vbX} ${vbY} ${vbW} ${vbH}`;

// Farm + nearest-major-city coordinates [lng, lat].
const geo = {
  everson: { farm: [-122.35, 48.92], city: [-122.48, 48.75] }, // Bellingham
  priest: { farm: [-116.91, 48.18], city: [-116.78, 47.68] }, // Coeur d'Alene
  durham: { farm: [-121.8, 39.65], city: [-121.49, 38.58] }, // Sacramento
  pine: { farm: [-111.46, 34.38], city: [-112.07, 33.45] }, // Phoenix
  lyons: { farm: [-105.27, 40.22], city: [-105.27, 40.01] }, // Boulder
  wellsville: { farm: [-111.93, 41.64], city: [-111.89, 40.76] }, // Salt Lake City
  bridgeport: { farm: [-97.76, 33.21], city: [-97.33, 32.76] }, // Fort Worth
  paola: { farm: [-94.88, 38.57], city: [-94.58, 39.1] }, // Kansas City
  cookeville: { farm: [-85.5, 36.16], city: [-86.78, 36.16] }, // Nashville
  statesville: { farm: [-80.89, 35.78], city: [-80.84, 35.23] }, // Charlotte
  defuniak: { farm: [-86.11, 30.72], city: [-86.5, 30.39] }, // Destin
  newport: { farm: [-82.72, 28.24], city: [-82.46, 27.95] }, // Tampa
  middleburg: { farm: [-81.86, 30.06], city: [-81.66, 30.33] }, // Jacksonville
};

const round = (n) => Math.round(n * 100) / 100;

const points = {};
for (const [id, { farm, city }] of Object.entries(geo)) {
  const f = projection(farm);
  const c = projection(city);
  if (!f || !c) throw new Error(`Point outside projection clip: ${id}`);
  points[id] = { fx: round(f[0]), fy: round(f[1]), cx: round(c[0]), cy: round(c[1]) };
}

const out = `// AUTO-GENERATED by scripts/generate-map-data.mjs — do not edit by hand.
// Accurate Albers-USA projection of the continental United States.

export const mapViewBox = "${viewBox}";

export const statesFillPath = ${JSON.stringify(statesFill)};

export const nationPath = ${JSON.stringify(nationPath)};

export const bordersPath = ${JSON.stringify(bordersPath)};

export type LocationPoint = { fx: number; fy: number; cx: number; cy: number };

export const locationPoints: Record<string, LocationPoint> = ${JSON.stringify(points, null, 2)};
`;

writeFileSync(resolve(root, "app/map-data.ts"), out);
console.log("Wrote app/map-data.ts");
console.log(`states fill path: ${statesFill.length} chars`);
console.log(`projected ${Object.keys(points).length} locations`);
